#!/usr/bin/env python3
"""Write the Android app's TrTable.java from tools/i18n/android/<lang>.json.

    python3 -I tools/i18n/android-table.py

Each JSON file maps the English text of a Tr.pick(...) call (notifications
and widgets) to its translation in that language; Spanish, English,
Portuguese and Japanese stay in the Java code. A text missing from a file
shows in English. Re-run after adding a Tr.pick text or a language.
"""

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "tools/i18n/android"
JAVA = ROOT / "app/android/app/src/main/java/com/metranos/trainradar"
OUT = JAVA / "TrTable.java"
LIT = r'"(?:[^"\\]|\\.)*"'
CALL = re.compile(r"Tr\.pick\(\s*[\w.()]+\s*,\s*" + LIT + r"\s*,\s*(" + LIT + r")", re.S)


def english():
    """The English texts of every Tr.pick call."""
    out = set()
    for f in JAVA.glob("*.java"):
        for m in CALL.findall(f.read_text("utf-8")):
            out.add(json.loads(m))
    return out


def fmt(s):
    """Java's %-placeholders, in order, positional ones by number."""
    found = re.findall(r"%(?:(\d+)\$)?([sd])", s)
    pos = [(int(n) if n else i + 1, t) for i, (n, t) in enumerate(found)]
    return sorted(pos)


def java(s):
    return json.dumps(s, ensure_ascii=False)


def main():
    texts = english()
    langs = {}
    bad = []
    for f in sorted(SRC.glob("*.json")):
        table = json.loads(f.read_text("utf-8"))
        lang = f.stem
        for en, tr in table.items():
            if en not in texts:
                bad.append(f"{lang}: no Tr.pick text {en!r}")
            elif fmt(en) != fmt(tr):
                bad.append(f"{lang}: placeholders differ in {tr!r} (English {en!r})")
        missing = texts - set(table)
        if missing:
            print(f"{lang}: {len(missing)} texts in English: {sorted(missing)}", file=sys.stderr)
        langs[lang] = {en: tr for en, tr in sorted(table.items()) if en in texts}
    if bad:
        print("\n".join(bad), file=sys.stderr)
        return 1
    lines = [
        "package com.metranos.trainradar;",
        "",
        "import java.util.HashMap;",
        "import java.util.Map;",
        "",
        "/** Generated by tools/i18n/android-table.py from tools/i18n/android/*.json: do not edit. */",
        "final class TrTable {",
        "    private TrTable() {}",
        "",
        "    private static final Map<String, Map<String, String>> BY = new HashMap<>();",
        "",
        "    /** The translation of an English text, or null. */",
        "    static String get(String lang, String en) {",
        "        Map<String, String> m = BY.get(lang);",
        "        return m == null ? null : m.get(en);",
        "    }",
        "",
        "    /** Whether the language has a table. */",
        "    static boolean known(String lang) {",
        "        return BY.containsKey(lang);",
        "    }",
        "",
        "    private static void put(String lang, String... pairs) {",
        "        Map<String, String> m = new HashMap<>();",
        "        for (int i = 0; i + 1 < pairs.length; i += 2) m.put(pairs[i], pairs[i + 1]);",
        "        BY.put(lang, m);",
        "    }",
        "",
    ]
    for lang, table in langs.items():
        lines.append(f"    private static void {lang}() {{")
        lines.append(f"        put({java(lang)},")
        pairs = [f"                {java(en)}, {java(tr)}" for en, tr in table.items()]
        lines.append(",\n".join(pairs) + ");")
        lines.append("    }")
        lines.append("")
    lines.append("    static {")
    for lang in langs:
        lines.append(f"        {lang}();")
    lines.append("    }")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", "utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(langs)} languages, {len(texts)} texts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
